/**
 * Turns the regions of Georgia (geoBoundaries ADM1, CC BY 3.0) into SVG paths for the geography map
 * (run: `node scripts/build-georgia-map.mjs`). Writes src/components/geography/georgia-shapes.ts.
 *
 * Projection: equirectangular, longitudes scaled by cos(42°) so shapes keep their proportions at
 * Georgia's latitude. The same projection is exported for placing cities and mountains.
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync("scripts/data/georgia-adm1.geojson", "utf8"));
const IDS = {
  Abkhazia: "abkhazia",
  Kakheti: "kakheti",
  "Kvemo Kartli": "kvemo-kartli",
  Tbilisi: "tbilisi",
  "Mtskheta-Mtianeti": "mtskheta-mtianeti",
  "Samtskhe–Javakheti": "samtskhe-javakheti",
  Adjara: "adjara",
  Guria: "guria",
  "Shida Kartli": "shida-kartli",
  Imereti: "imereti",
  "Racha-Lechkhumi and Kvemo Svaneti": "racha-lechkhumi",
  "Samegrelo-Zemo Svaneti": "samegrelo-zemo-svaneti",
};

const K = Math.cos((42 * Math.PI) / 180);
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
const rings = (g) => (g.type === "MultiPolygon" ? g.coordinates.flat() : g.coordinates);
for (const f of src.features)
  for (const ring of rings(f.geometry))
    for (const [lon, lat] of ring) {
      minX = Math.min(minX, lon * K);
      maxX = Math.max(maxX, lon * K);
      minY = Math.min(minY, -lat);
      maxY = Math.max(maxY, -lat);
    }
const W = 1000;
const PAD = 10;
const scale = (W - 2 * PAD) / (maxX - minX);
const H = Math.round((maxY - minY) * scale + 2 * PAD);
const project = (lon, lat) => [PAD + (lon * K - minX) * scale, PAD + (-lat - minY) * scale];

const regions = src.features.map((f) => {
  const id = IDS[f.properties.shapeName];
  if (!id) throw new Error(`unknown region ${f.properties.shapeName}`);
  let d = "";
  let area = 0, cx = 0, cy = 0;
  for (const ring of rings(f.geometry)) {
    const pts = ring.map(([lon, lat]) => project(lon, lat));
    d += "M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z";
    // Polygon centroid (for the region's name label).
    for (let i = 0; i < pts.length - 1; i++) {
      const [x0, y0] = pts[i];
      const [x1, y1] = pts[i + 1];
      const a = x0 * y1 - x1 * y0;
      area += a;
      cx += (x0 + x1) * a;
      cy += (y0 + y1) * a;
    }
  }
  return { id, d, cx: +(cx / (3 * area)).toFixed(1), cy: +(cy / (3 * area)).toFixed(1) };
});

const out = `// Generated by scripts/build-georgia-map.mjs from geoBoundaries (CC BY 3.0). Do not edit by hand.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};

const K = ${K};
const SCALE = ${scale};
const MIN_X = ${minX};
const MIN_Y = ${minY};
const PAD = ${PAD};

/** Longitude/latitude → map coordinates (same projection as the region shapes). */
export function project(lon: number, lat: number): [number, number] {
  return [PAD + (lon * K - MIN_X) * SCALE, PAD + (-lat - MIN_Y) * SCALE];
}

export const REGION_SHAPES: { id: string; d: string; cx: number; cy: number }[] = ${JSON.stringify(regions)};
`;
writeFileSync("src/components/geography/georgia-shapes.ts", out);
console.log(`map ${W}×${H}, ${regions.length} regions, ${(out.length / 1024).toFixed(0)} KB`);
