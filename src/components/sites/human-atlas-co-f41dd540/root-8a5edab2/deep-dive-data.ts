/**
 * "შიგნით ჩახედვა" — deep-dive content. Every atlas structure maps to one tissue template that
 * describes it from the outermost layer down to the cells. All text is original Georgian written for
 * school students; `visual` lines double as the colour/texture brief for the illustrations.
 */

export type LayerPattern = "solid" | "porous" | "fibrous" | "wavy" | "cells" | "liquid" | "striated";

export interface DiveLayer {
  id: string;
  name: string;
  /** 1–2 sentence explanation shown when the layer is tapped. */
  tooltip: string;
  /** Colour · surface · density · state (guide for the illustration and 3D texturing). */
  visual: string;
  color: string;
  pattern: LayerPattern;
  /** Relative thickness in the cross-section drawing. */
  thickness: number;
}

export interface DiveMicro {
  id: string;
  name: string;
  tooltip: string;
}

