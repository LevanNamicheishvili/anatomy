export const SOUND_WATER = 1500;

export function depthAt(km: number) {
  for (let i = 1; i < PROFILE.length; i++) {
    if (km <= PROFILE[i][0]) {
      const [x0, y0] = PROFILE[i - 1];
      const [x1, y1] = PROFILE[i];
      return y0 + ((y1 - y0) * (km - x0)) / (x1 - x0);
    }
  }
  return 0;
}
