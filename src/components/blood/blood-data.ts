export const GROUP_NAMES: Record<BloodGroup, string> = { O: "I (0)", A: "II (A)", B: "III (B)", AB: "IV (AB)" };

const ANTIGENS: Record<BloodGroup, string[]> = { O: [], A: ["A"], B: ["B"], AB: ["A", "B"] };

/** Red-cell transfusion: every antigen on the donor's cells must also be the recipient's own. */
export function compatible(donor: BloodGroup, donorRh: boolean, recipient: BloodGroup, recipientRh: boolean) {
  const abo = ANTIGENS[donor].every((a) => ANTIGENS[recipient].includes(a));
  const rh = !donorRh || recipientRh;
  return { ok: abo && rh, abo, rh };
}
